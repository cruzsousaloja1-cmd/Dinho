/**
 * Faz upload da foto de perfil para o Supabase Storage (buckets 'avatars' / 'fotos') com compressão e limite de 2MB.
 * Retorna a URL pública (com cache-buster) quando o Storage aceitar, ou a imagem comprimida + erro real caso o Storage falhe.
 */
export async function uploadProfilePhotoSupabase(params: {
  photo: File | string;
  identifier?: string;
}): Promise<{
  url: string;
  compressedDataUrl: string;
  storageUploaded: boolean;
  error?: string;
}> {
  const { photo, identifier } = params;
  if (!photo) {
    return { url: '', compressedDataUrl: '', storageUploaded: false, error: 'Nenhuma foto selecionada.' };
  }

  if (typeof photo === 'string') {
    const trimmed = photo.trim();
    if (!trimmed) {
      return { url: '', compressedDataUrl: '', storageUploaded: false, error: 'Foto vazia.' };
    }
    if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) {
      const cleanHttp = trimmed.replace(/([?&])(t|v)=\d+(&|$)/g, (_, p1, _p2, p3) => (p3 === '&' ? p1 : '')).replace(/[?&]$/, '');
      return { url: cleanHttp, compressedDataUrl: cleanHttp, storageUploaded: true };
    }
  } else {
    const sizeErr = validatePhotoMax2MB(photo);
    if (sizeErr) {
      return { url: '', compressedDataUrl: '', storageUploaded: false, error: sizeErr };
    }
  }

  let compressedDataUrl = '';
  try {
    compressedDataUrl = await compressImageToMax200KB(photo);
  } catch (err: any) {
    return {
      url: '',
      compressedDataUrl: '',
      storageUploaded: false,
      error: err?.message || 'Falha ao comprimir a foto selecionada.',
    };
  }

  if (!compressedDataUrl || !compressedDataUrl.startsWith('data:image')) {
    return {
      url: '',
      compressedDataUrl: '',
      storageUploaded: false,
      error: 'Formato de imagem inválido.',
    };
  }

  if (compressedDataUrl.length > MAX_PHOTO_FILE_BYTES) {
    return {
      url: '',
      compressedDataUrl: '',
      storageUploaded: false,
      error: 'A imagem comprimida ainda ultrapassa 2MB. Escolha outra foto.',
    };
  }

  const blob = dataUrlToJpegBlob(compressedDataUrl);
  if (!blob) {
    return {
      url: compressedDataUrl,
      compressedDataUrl,
      storageUploaded: false,
      error: 'Não foi possível preparar a imagem para upload.',
    };
  }

  const safeSlug = String(identifier || 'usuario')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '_')
    .replace(/_+/g, '_')
    .slice(0, 40) || 'usuario';
  const filePath = `perfis/${safeSlug}_${Date.now()}.jpg`;
  const candidateBuckets = ['avatars', 'fotos'];
  let lastStorageError = '';

  for (const bucket of candidateBuckets) {
    let uploadRes = await supabase.storage
      .from(bucket)
      .upload(filePath, blob, {
        contentType: 'image/jpeg',
        cacheControl: '3600',
        upsert: true,
      });

    if (uploadRes.error) {
      const msgLower = (uploadRes.error.message || '').toLowerCase();
      if (msgLower.includes('bucket') && msgLower.includes('not found')) {
        try {
          await supabase.storage.createBucket(bucket, { public: true });
          uploadRes = await supabase.storage
            .from(bucket)
            .upload(filePath, blob, {
              contentType: 'image/jpeg',
              cacheControl: '3600',
              upsert: true,
            });
        } catch {}
      }
    }

    if (!uploadRes.error) {
      const { data: pubData } = supabase.storage.from(bucket).getPublicUrl(filePath);
      const publicUrl = pubData?.publicUrl ? String(pubData.publicUrl).trim() : '';
      if (publicUrl) {
        return {
          url: publicUrl,
          compressedDataUrl,
          storageUploaded: true,
        };
      }
    } else {
      lastStorageError = uploadRes.error.message || `Falha ao enviar para bucket "${bucket}"`;
    }
  }

  return {
    url: compressedDataUrl,
    compressedDataUrl,
    storageUploaded: false,
    error: lastStorageError || 'Falha no upload para o Storage do Supabase.',
  };
}

function filterPayloadToExistingColumns(
  payload: Record<string, any>,
  knownCols: Set<string> | null,
  requiredKeys: Set<string>
): void {
  // Nunca inventar avatar, bau, cor, cpf, lat, lng, online, plano_ativo, status se não existirem no banco
  for (const key of Object.keys(payload)) {
    if (requiredKeys.has(key)) continue;
    if (knownCols && knownCols.size > 0) {
      if (!knownCols.has(key)) {
        delete payload[key];
      }
    } else if (FORBIDDEN_INVENTED_COLS.has(key)) {
      delete payload[key];
    }
  }
}

/**
 * Seleciona colunas seguras de public.usuarios sem nunca solicitar a coluna `senha` nem colunas inexistentes
 */
export async function selectSafeUsuariosRows(applyFilter?: (q: any) => any): Promise<{ data: any[] | null; error: any }> {
  const knownCols = await getUsuariosTableColumns();
  let cols = knownCols && knownCols.size > 0
    ? SAFE_USUARIO_COLS_LIST.filter((c) => knownCols.has(c))
    : ['id', 'created_at', 'nome', 'email', 'e-mail', 'celular', 'whatsapp', 'login', 'tipo', 'categoria', 'placa', 'modelo', 'ano', 'cnh', 'foto', 'avatar', 'rating', 'saldo', 'divida'];

  if (cols.length === 0) cols = ['id', 'nome', 'tipo'];
  let useFilter = Boolean(applyFilter);

  for (let attempt = 0; attempt < 30; attempt++) {
    const selectClause = cols.map((c) => (c.includes('-') ? `"${c}"` : c)).join(',');
    let query: any = supabase.from('usuarios').select(selectClause);
    if (useFilter && applyFilter) {
      query = applyFilter(query);
    }
    const { data, error } = await query;
    if (!error) {
      return { data: Array.isArray(data) ? data.map(stripSensitiveUserFields) : [], error: null };
    }
    const msg = error.message || '';
    if (!isMissingColumnError(error)) {
      return { data: null, error };
    }
    const missing = extractMissingColumnFromSupabaseError(msg);
    if (missing && cols.includes(missing)) {
      cols = cols.filter((c) => c !== missing);
      if (cols.length === 0) return { data: [], error: null };
      continue;
    }
    let removed = false;
    for (const c of cols) {
      if (msg.includes(c)) {
        cols = cols.filter((item) => item !== c);
        removed = true;
        break;
      }
    }
    if (removed && cols.length > 0) continue;
    if (useFilter) {
      useFilter = false;
      continue;
    }
    return { data: [], error: null };
  }
  return { data: [], error: null };
}

