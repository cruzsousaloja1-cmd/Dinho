/**
 * Salva corrida na tabela public.corridas no Supabase (sem enviar `id` manual no insert)
 */
export async function saveCorridaSupabase(
  ride: Ride,
  currentUser: AppUser | null
): Promise<{ success: boolean; id?: string; error?: string }> {
  try {
    const rawPassengerId = (ride as any).passengerId || currentUser?.id || '';
    const rawDriverId = ride.driver?.id || '';

    const payload: any = {
      email_passageiro: ((ride as any).passengerEmail || currentUser?.email || '').toLowerCase().trim(),
      nome_passageiro: ride.passengerName || currentUser?.name || 'Passageiro',
      email_motorista: (ride.driver?.email || '').toLowerCase().trim(),
      nome_motorista: ride.driver?.name || '',
      origem: ride.pickup,
      destino: ride.destination,
      origem_texto: ride.pickup?.address || '',
      destino_texto: ride.destination?.address || '',
      valor: Number(ride.price.toFixed(2)),
      categoria: ride.category,
      status: ride.status || 'completed',
      forma_pagamento: ride.paymentMethod || 'pix',
      rating_dado: ride.ratingGivenToDriver ?? null,
      comentario: ride.ratingComment ?? null,
      detalhe_problema: (ride as any).issueComment ?? null,
      codigo_confirmacao: ride.confirmationCode || '',
      data: ride.createdAt || new Date().toISOString(),
    };

    if (/^\d+$/.test(String(rawPassengerId))) {
      payload.id_passageiro = Number(rawPassengerId);
    }
    if (/^\d+$/.test(String(rawDriverId))) {
      payload.id_motorista = Number(rawDriverId);
    }

    // Se a corrida já possui ID numérico gerado pelo Supabase, faz update
    if (ride.id && /^\d+$/.test(String(ride.id))) {
      const { data: updData, error: updErr } = await supabase
        .from('corridas')
        .update(payload)
        .eq('id', Number(ride.id))
        .select();
      if (!updErr && updData && updData.length > 0) {
        return { success: true, id: String(updData[0].id) };
      }
    }

    // Novo registro: INSERT sem campo `id` (Supabase gera o bigint automático)
    const optionalCols = [
      'codigo_confirmacao',
      'id_passageiro',
      'id_motorista',
      'detalhe_problema',
      'comentario',
      'rating_dado',
      'forma_pagamento',
      'origem_texto',
      'destino_texto',
      'nome_passageiro',
      'nome_motorista',
    ];

    for (let attempt = 0; attempt < 6; attempt++) {
      const { data, error } = await supabase.from('corridas').insert([payload]).select();
      if (!error) {
        return { success: true, id: data?.[0]?.id !== undefined ? String(data[0].id) : undefined };
      }

      const msg = error.message || '';
      let changed = false;
      for (const col of optionalCols) {
        if (col in payload && msg.includes(col)) {
          delete payload[col];
          changed = true;
        }
      }
      if (!changed && msg.includes('bigint')) {
        if ('id_passageiro' in payload) {
          delete payload.id_passageiro;
          changed = true;
        }
        if ('id_motorista' in payload) {
          delete payload.id_motorista;
          changed = true;
        }
      }
      if (changed) continue;

      console.warn('Aviso Supabase ao salvar corrida:', msg);
      return { success: false, error: msg };
    }

    return { success: false, error: 'Não foi possível salvar corrida no Supabase.' };
  } catch (err: any) {
    console.warn('Erro ao salvar corrida no Supabase:', err?.message || err);
    return { success: false, error: err?.message };
  }
}

