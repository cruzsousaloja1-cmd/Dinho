export function normalizeRideCategory(rawCat?: string): 'economica' | 'confort' | 'moto_passageiro' | 'moto_entrega' {
  const c = String(rawCat || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
  if (c.includes('confort')) return 'confort';
  if (c.includes('entrega') || c.includes('flash')) return 'moto_entrega';
  if (c.includes('moto')) return 'moto_passageiro';
  return 'economica';
}

