/**
 * Salva ou atualiza usuário na tabela public.usuarios no Supabase (sem enviar `id` manual)
 */
export async function saveUsuarioSupabase(user: {
  codigo_usuario?: string;
  nome: string;
  email: string;
  celular?: string;
  whatsapp?: string;
  login?: string;
  senha?: string;
  tipo?: string;
  categoria?: string;
  placa?: string;
  modelo?: string;
  ano?: number | string;
  cnh?: string;
  foto?: string;
  avatar?: string;
  rating?: number;
  saldo?: number;
  plano_ativo?: boolean;
}): Promise<{ success: boolean; data?: any; error?: string }> {
  try {
    const cleanEmail = user.email.toLowerCase().trim();

    // Verifica se já existe na nuvem
    const existing = await getUsuarioSupabase(cleanEmail);

    if (existing) {
      // Faz UPDATE sem alterar `id`
      const updateData: any = {
        nome: user.nome,
        celular: user.celular || user.whatsapp || existing.celular || '',
        senha: user.senha || existing.senha,
        tipo: user.tipo || existing.tipo || 'passenger',
        categoria: user.categoria || existing.categoria,
        placa: user.placa || existing.placa,
        modelo: user.modelo || existing.modelo,
        ano: user.ano ? String(user.ano) : existing.ano,
        cnh: user.cnh || existing.cnh,
      };
      if (user.foto || user.avatar) {
        updateData.avatar = user.foto || user.avatar;
      }

      let { data, error } = await supabase
        .from('usuarios')
        .update(updateData)
        .eq('id', existing.id)
        .select();

      if (error && error.message?.includes('avatar')) {
        delete updateData.avatar;
        const retry = await supabase
          .from('usuarios')
          .update(updateData)
          .eq('id', existing.id)
          .select();
        data = retry.data;
        error = retry.error;
      }

      if (error) return { success: false, error: error.message };
      return { success: true, data: data?.[0] };
    } else {
      // Faz INSERT direto sem `id` manual
      return insertUsuarioSupabase({
        codigo_usuario: user.codigo_usuario,
        nome: user.nome,
        email: cleanEmail,
        celular: user.celular || user.whatsapp || '',
        whatsapp: user.whatsapp || user.celular || '',
        login: user.login || cleanEmail,
        senha: user.senha || '123456',
        tipo: user.tipo || 'passenger',
        categoria: user.categoria,
        placa: user.placa,
        modelo: user.modelo,
        ano: user.ano,
        cnh: user.cnh,
        foto: user.foto || user.avatar,
        avatar: user.avatar || user.foto,
      });
    }
  } catch (err: any) {
    return { success: false, error: err?.message || 'Falha de conexão com Supabase' };
  }
}

/**
 * Busca usuário por e-mail ou login no Supabase (suporta 'e-mail', 'email' e 'login')
 */
export async function getUsuarioSupabase(emailOrLogin: string): Promise<any | null> {
  const clean = emailOrLogin.trim().toLowerCase();
  if (!clean) return null;

  try {
    // 1. Tenta por 'e-mail'
    const { data: byHyphen } = await supabase
      .from('usuarios')
      .select('*')
      .eq('e-mail', clean)
      .maybeSingle();

    if (byHyphen) return byHyphen;

    // 2. Tenta por 'email'
    const { data: byNoHyphen } = await supabase
      .from('usuarios')
      .select('*')
      .eq('email', clean)
      .maybeSingle();

    if (byNoHyphen) return byNoHyphen;

    // 3. Tenta por 'login'
    const { data: byLogin } = await supabase
      .from('usuarios')
      .select('*')
      .eq('login', clean)
      .maybeSingle();

    if (byLogin) return byLogin;
  } catch (err) {
    console.warn('Aviso ao consultar Supabase:', err);
  }

  return null;
}

/**
 * Atualiza a senha do usuário na tabela public.usuarios no Supabase
 * Se for o administrador (admin@race.com.br) e ainda não houver linha em public.usuarios, cria a linha para persistir a nova senha na nuvem.
 */
export async function updatePasswordSupabase(
  identifier: string,
  newPassword: string,
  fallbackNome?: string
): Promise<{ success: boolean; error?: string }> {
  const clean = identifier.trim().toLowerCase();
  if (!clean || !newPassword) {
    return { success: false, error: 'Identificador ou senha inválidos.' };
  }

  try {
    // 1. Tenta atualizar por 'e-mail'
    const resHyphen = await supabase
      .from('usuarios')
      .update({ senha: newPassword })
      .eq('e-mail', clean)
      .select();

    if (!resHyphen.error && resHyphen.data && resHyphen.data.length > 0) {
      return { success: true };
    }

    // 2. Tenta atualizar por 'email'
    const resNoHyphen = await supabase
      .from('usuarios')
      .update({ senha: newPassword })
      .eq('email', clean)
      .select();

    if (!resNoHyphen.error && resNoHyphen.data && resNoHyphen.data.length > 0) {
      return { success: true };
    }

    // 3. Tenta atualizar por 'login'
    const resLogin = await supabase
      .from('usuarios')
      .update({ senha: newPassword })
      .eq('login', clean)
      .select();

    if (!resLogin.error && resLogin.data && resLogin.data.length > 0) {
      return { success: true };
    }

    // 4. Se ainda não existir linha para o usuário (ex: admin@race.com.br master), insere na tabela public.usuarios
    if (clean === 'admin@race.com.br') {
      const inserted = await insertUsuarioSupabase({
        nome: fallbackNome || 'Administrador Geral',
        email: clean,
        celular: '(19) 99999-0000',
        senha: newPassword,
        tipo: 'admin',
      });
      if (inserted.success) {
        return { success: true };
      }
      return { success: false, error: inserted.error };
    }

    // Caso tenha ocorrido erro de rede/schema mas não impediu o fluxo local
    const anyError = resHyphen.error || resNoHyphen.error || resLogin.error;
    if (anyError) {
      return { success: false, error: anyError.message };
    }

    return { success: false, error: 'Usuário não encontrado na tabela public.usuarios do Supabase.' };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Erro ao atualizar senha no Supabase.' };
  }
}

