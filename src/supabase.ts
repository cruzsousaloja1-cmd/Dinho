/**
 * Busca corridas filtradas estritamente de acordo com quem está logado
 */
export async function getCorridasSupabase(currentUser: AppUser | null): Promise<Ride[]> {
  if (!currentUser) return [];

  const cleanEmail = (currentUser.email || '').toLowerCase().trim();
  const isAdmin =
    currentUser.role === 'admin' ||
    currentUser.isAdmin ||
    String(currentUser.tipo || '').toUpperCase() === 'ADM' ||
    cleanEmail === 'admin@race.com.br';

  const hasNumericId = /^\d+$/.test(String(currentUser.id || ''));

  try {
    let query = supabase.from('corridas').select('*').order('id', { ascending: false });

    if (!isAdmin) {
      const isDriverOrMotoboy =
        currentUser.role === 'driver' ||
        currentUser.role === 'motoboy' ||
        currentUser.tipo === 'driver' ||
        currentUser.tipo === 'motoboy' ||
        currentUser.tipo === 'motorista_economico' ||
        currentUser.tipo === 'motorista_confort' ||
        currentUser.tipo === 'motoboy_passageiro' ||
        currentUser.tipo === 'motoboy_entregas';

      if (isDriverOrMotoboy) {
        query = hasNumericId
          ? query.or(`id_motorista.eq.${currentUser.id},email_motorista.eq.${cleanEmail}`)
          : query.eq('email_motorista', cleanEmail);
      } else {
        query = hasNumericId
          ? query.or(`id_passageiro.eq.${currentUser.id},email_passageiro.eq.${cleanEmail}`)
          : query.eq('email_passageiro', cleanEmail);
      }
    }

    const { data, error } = await query;
    if (error) {
      // Fallback caso a tabela use passageiro_id / motorista_id sem id_passageiro / id_motorista
      let fallbackQuery = supabase.from('corridas').select('*').order('id', { ascending: false });
      if (!isAdmin && hasNumericId) {
        const isDriverOrMotoboy =
          currentUser.role === 'driver' ||
          currentUser.role === 'motoboy' ||
          currentUser.tipo === 'driver' ||
          currentUser.tipo === 'motoboy' ||
          currentUser.tipo === 'motorista_economico' ||
          currentUser.tipo === 'motorista_confort' ||
          currentUser.tipo === 'motoboy_passageiro' ||
          currentUser.tipo === 'motoboy_entregas';
        fallbackQuery = isDriverOrMotoboy
          ? fallbackQuery.eq('motorista_id', Number(currentUser.id))
          : fallbackQuery.eq('passageiro_id', Number(currentUser.id));
        const fb = await fallbackQuery;
        if (!fb.error && fb.data) {
          return (fb.data as SupabaseCorridaRow[]).map(mapSupabaseCorridaToRide);
        }
      }
      console.warn('Aviso ao consultar corridas no Supabase:', error.message);
      return [];
    }

    if (!data || data.length === 0) return [];
    return (data as SupabaseCorridaRow[]).map(mapSupabaseCorridaToRide);
  } catch (err) {
    console.warn('Erro ao consultar corridas no Supabase:', err);
    return [];
  }
}

/**
 * Salva pagamento / repasse na tabela public.pagamentos no Supabase (sem enviar `id` manual no insert)
 */
export async function savePagamentoSupabase(pagamento: {
  id?: string | number;
  id_motorista?: string | number;
  nome_motorista?: string;
  email_motorista?: string;
  valor?: number;
  tipo?: string;
  status?: string;
  chave_pix?: string;
  comprovante_url?: string;
}): Promise<{ success: boolean; id?: string; error?: string }> {
  try {
    const payload: any = {
      nome_motorista: pagamento.nome_motorista || '',
      email_motorista: (pagamento.email_motorista || '').toLowerCase().trim(),
      valor: pagamento.valor ?? 0.0,
      tipo: pagamento.tipo || 'corrida',
      status: pagamento.status || 'pending',
      data: new Date().toISOString(),
      chave_pix: pagamento.chave_pix || '',
      comprovante_url: pagamento.comprovante_url || '',
    };

    if (pagamento.id_motorista !== undefined && /^\d+$/.test(String(pagamento.id_motorista))) {
      payload.id_motorista = Number(pagamento.id_motorista);
    }

    // Se já possui ID numérico no Supabase, faz update
    if (pagamento.id !== undefined && /^\d+$/.test(String(pagamento.id))) {
      const { data: updData, error: updErr } = await supabase
        .from('pagamentos')
        .update(payload)
        .eq('id', Number(pagamento.id))
        .select();
      if (!updErr && updData && updData.length > 0) {
        return { success: true, id: String(updData[0].id) };
      }
    }

    // Novo pagamento: INSERT sem `id` (Supabase gera o bigint automático)
    for (let attempt = 0; attempt < 4; attempt++) {
      const { data, error } = await supabase.from('pagamentos').insert([payload]).select();
      if (!error) {
        return { success: true, id: data?.[0]?.id !== undefined ? String(data[0].id) : undefined };
      }

      const msg = error.message || '';
      if (msg.includes('bigint') && 'id_motorista' in payload) {
        delete payload.id_motorista;
        continue;
      }
      if (msg.includes('comprovante_url') && 'comprovante_url' in payload) {
        delete payload.comprovante_url;
        continue;
      }
      console.warn('Aviso Supabase ao salvar pagamento:', msg);
      return { success: false, error: msg };
    }

    return { success: false, error: 'Não foi possível salvar pagamento no Supabase.' };
  } catch (err: any) {
    console.warn('Erro ao salvar pagamento no Supabase:', err?.message || err);
    return { success: false, error: err?.message };
  }
}

