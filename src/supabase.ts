export async function acceptCorridaSupabase(
  rideId: string | number,
  driver: Driver
): Promise<{ success: boolean; error?: string }> {
  // Envia broadcast em tempo real para o passageiro imediatamente
  broadcastCorridaEvent('corrida_aceita', {
    id: String(rideId || ''),
    status: 'aceita',
    motorista_id: driver.id,
    nome_motorista: driver.name,
    email_motorista: driver.email,
    driver,
  });

  if (!rideId || !/^\d+$/.test(String(rideId))) {
    return { success: false, error: 'ID inválido para aceite' };
  }
  try {
    const updatePayload: any = {
      status: 'aceita',
      email_motorista: (driver.email || '').toLowerCase().trim(),
      nome_motorista: driver.name || '',
    };
    if (/^\d+$/.test(String(driver.id || ''))) {
      updatePayload.id_motorista = Number(driver.id);
      updatePayload.motorista_id = Number(driver.id);
    }

    const optionalCols = ['id_motorista', 'motorista_id', 'email_motorista', 'nome_motorista'];
    for (let attempt = 0; attempt < 6; attempt++) {
      const { error } = await supabase
        .from('corridas')
        .update(updatePayload)
        .eq('id', Number(rideId));

      if (!error) {
        return { success: true };
      }

      const msg = error.message || '';
      let changed = false;
      for (const col of optionalCols) {
        if (col in updatePayload && msg.includes(col)) {
          delete updatePayload[col];
          changed = true;
        }
      }
      if (!changed) {
        return { success: false, error: msg };
      }
    }
    return { success: false, error: 'Erro ao aceitar corrida' };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Erro ao aceitar corrida' };
  }
}

