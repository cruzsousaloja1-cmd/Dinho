/**
 * Hidrata corridas com a foto real (colunas `foto` OU `avatar`) e dados do motorista/passageiro direto do Supabase
 * sem precisar recarregar a página.
 */
export async function hydrateRidesWithUserPhotosSupabase(rides: Ride[]): Promise<Ride[]> {
  if (!Array.isArray(rides) || rides.length === 0) return rides;

  const needsHydration = rides.some((r) => {
    const missingPassenger = !r.passengerAvatar || !r.passengerPhone;
    const missingDriver = Boolean(
      r.driver && (!r.driver.avatar || !r.driver.vehiclePlate || !r.driver.vehicleModel || !r.driver.phone)
    );
    return missingPassenger || missingDriver;
  });

  if (!needsHydration) return rides;

  try {
    const lookupMap = await getUsuariosHydrationLookupMap(false);

    // Garante busca individual por RPC caso RLS restrinja a listagem completa
    const individualFetches: Promise<void>[] = [];
    const checkedEmails = new Set<string>();

    const ensureEmailLookup = (email?: string, id?: string) => {
      const cleanEmail = String(email || '').trim().toLowerCase();
      const cleanId = String(id || '').trim();
      const alreadyHas =
        (cleanId && lookupMap.has(`id:${cleanId}`)) ||
        (cleanEmail && lookupMap.has(`email:${cleanEmail}`));
      if (alreadyHas) return;
      if (cleanEmail && !checkedEmails.has(cleanEmail)) {
        checkedEmails.add(cleanEmail);
        individualFetches.push(
          getUsuarioSupabase(cleanEmail)
            .then((u) => {
              if (u) indexUsuarioRowIntoMap(lookupMap, u);
            })
            .catch(() => {})
        );
      }
    };

    for (const r of rides) {
      if (!r.passengerAvatar) {
        ensureEmailLookup(r.passengerEmail, r.passengerId);
      }
      if (r.driver && (!r.driver.avatar || !r.driver.vehiclePlate)) {
        ensureEmailLookup(r.driver.email, r.driver.id);
      }
    }

    if (individualFetches.length > 0) {
      await Promise.all(individualFetches);
    }

    return rides.map((r) => {
      const pRow =
        (r.passengerId && lookupMap.get(`id:${String(r.passengerId)}`)) ||
        (r.passengerEmail && lookupMap.get(`email:${String(r.passengerEmail).trim().toLowerCase()}`)) ||
        null;

      const dRow = r.driver
        ? (r.driver.id && lookupMap.get(`id:${String(r.driver.id)}`)) ||
          (r.driver.email && lookupMap.get(`email:${String(r.driver.email).trim().toLowerCase()}`)) ||
          null
        : null;

      const pPhoto = pRow ? extractPhotoFromRow(pRow) : '';
      const dPhoto = dRow ? extractPhotoFromRow(dRow) : '';

      const hydratedDriver = r.driver
        ? {
            ...r.driver,
            avatar: r.driver.avatar || dPhoto || '',
            name: r.driver.name || dRow?.nome || 'Motorista',
            phone: r.driver.phone || dRow?.celular || dRow?.whatsapp || '',
            vehicleModel: r.driver.vehicleModel || dRow?.modelo || '',
            vehiclePlate: r.driver.vehiclePlate || dRow?.placa || '',
            vehicleColor: r.driver.vehicleColor || dRow?.cor || '',
            vehicleYear: r.driver.vehicleYear || Number(dRow?.ano) || 2023,
            rating: r.driver.rating || (typeof dRow?.rating === 'number' ? dRow.rating : 0),
          }
        : undefined;

      return {
        ...r,
        passengerAvatar: r.passengerAvatar || pPhoto || '',
        passengerPhone: r.passengerPhone || pRow?.celular || pRow?.whatsapp || '',
        passengerName:
          r.passengerName && r.passengerName !== 'Passageiro'
            ? r.passengerName
            : pRow?.nome || r.passengerName || 'Passageiro',
        passengerRating:
          r.passengerRating || (typeof pRow?.rating === 'number' ? pRow.rating : 0),
        driver: hydratedDriver,
      };
    });
  } catch {
    return rides;
  }
}

// Canal Realtime compartilhado 'corridas' (postgres_changes + broadcast instantâneo)
type CorridaRealtimeListener = {
  onInsert?: (ride: Ride, raw: any) => void;
  onUpdate?: (ride: Ride, raw: any) => void;
};

const corridasRealtimeListeners = new Set<CorridaRealtimeListener>();
let sharedCorridasChannel: any = null;
let sharedCorridasChannelSubscribed = false;

function ensureSharedCorridasChannel() {
  if (sharedCorridasChannel) return sharedCorridasChannel;

  const notifyHydratedInsert = async (ride: Ride, raw: any) => {
    const [hydrated] = await hydrateRidesWithUserPhotosSupabase([ride]).catch(() => [ride]);
    corridasRealtimeListeners.forEach((l) => {
      try {
        l.onInsert?.(hydrated || ride, raw);
      } catch {}
    });
  };

  const notifyHydratedUpdate = async (ride: Ride, raw: any) => {
    const [hydrated] = await hydrateRidesWithUserPhotosSupabase([ride]).catch(() => [ride]);
    corridasRealtimeListeners.forEach((l) => {
      try {
        l.onUpdate?.(hydrated || ride, raw);
      } catch {}
    });
  };

  sharedCorridasChannel = supabase
    .channel('corridas')
    .on(
      'postgres_changes',
      { event: 'INSERT', schema: 'public', table: 'corridas' },
      (payload: any) => {
        if (!payload?.new) return;
        const ride = mapSupabaseCorridaToRide(payload.new as SupabaseCorridaRow);
        notifyHydratedInsert(ride, payload.new);
      }
    )
    .on(
      'postgres_changes',
      { event: 'UPDATE', schema: 'public', table: 'corridas' },
      (payload: any) => {
        if (!payload?.new) return;
        const ride = mapSupabaseCorridaToRide(payload.new as SupabaseCorridaRow);
        notifyHydratedUpdate(ride, payload.new);
      }
    )
    .on('broadcast', { event: 'nova_corrida' }, (msg: any) => {
      const row = msg?.payload;
      if (!row) return;
      const ride = row.pickup && row.destination ? (row as Ride) : mapSupabaseCorridaToRide(row as SupabaseCorridaRow);
      notifyHydratedInsert(ride, row);
    })
    .on('broadcast', { event: 'corrida_aceita' }, (msg: any) => {
      const row = msg?.payload;
      if (!row) return;
      const ride = row.pickup && row.destination ? (row as Ride) : mapSupabaseCorridaToRide(row as SupabaseCorridaRow);
      notifyHydratedUpdate(ride, row);
    });

  sharedCorridasChannel.subscribe((status: string) => {
    sharedCorridasChannelSubscribed = status === 'SUBSCRIBED';
  });

  return sharedCorridasChannel;
}

export function subscribeToCorridasRealtime(listener: CorridaRealtimeListener): () => void {
  corridasRealtimeListeners.add(listener);
  ensureSharedCorridasChannel();
  return () => {
    corridasRealtimeListeners.delete(listener);
  };
}

export async function broadcastCorridaEvent(
  eventName: 'nova_corrida' | 'corrida_aceita',
  payload: any
): Promise<void> {
  try {
    const ch = ensureSharedCorridasChannel();
    if (!sharedCorridasChannelSubscribed) {
      await new Promise((resolve) => setTimeout(resolve, 250));
    }
    await ch.send({
      type: 'broadcast',
      event: eventName,
      payload,
    });
  } catch {}
}

/**
 * Salva corrida na tabela public.corridas no Supabase (sem enviar `id` manual no insert)
 */
export async function saveCorridaSupabase(
  ride: Ride,
  currentUser: AppUser | null
): Promise<{ success: boolean; id?: string; error?: string }> {
  try {
    const rawPassengerId = (ride as any).passengerId || currentUser?.id || '';
    const rawDriverId = ride.driver?.id || '';

    const normalizedPaymentMethod =
      ride.paymentMethod === 'money' || ride.paymentMethod === 'dinheiro'
        ? 'dinheiro'
        : ride.paymentMethod === 'credit_card'
        ? 'credit_card'
        : 'pix';

    const rawSt = String(ride.status || 'procurando').toLowerCase().trim();
    const normalizedStatus =
      rawSt === 'searching' || rawSt === 'procurando_motorista' ? 'procurando' : rawSt;

    const isCash = normalizedPaymentMethod === 'dinheiro';
    const isAsaasConfirmed =
      ride.asaasStatus === 'RECEIVED' || ride.asaasStatus === 'CONFIRMED';

    // Bloqueia gravação de corrida procurando sem pagamento real no Asaas (exceto dinheiro)
    if (!isCash && normalizedStatus === 'procurando' && !isAsaasConfirmed) {
      return { success: false, error: 'Pague primeiro no Asaas para chamar o motorista.' };
    }

    // Bloqueia gravação de Motoboy Entregas incompleta antes do motoboy ver a entrega
    if (
      normalizedStatus === 'procurando' &&
      normalizeRideCategory(ride.category) === 'moto_entrega' &&
      !isDeliveryRideCompleteForDriver(ride)
    ) {
      return {
        success: false,
        error: 'Falta preencher para entrega: descrição, peso, nome e telefone de quem recebe.',
      };
    }

    const totalPrice = Number((ride.price || 0).toFixed(2));
    const driverEarnings = Number((ride.driverEarnings ?? totalPrice * 0.85).toFixed(2));
    const raceFee = Number((ride.platformFee ?? totalPrice * 0.15).toFixed(2));
    const nowIso = ride.createdAt || new Date().toISOString();

    const origemWithMeta = ride.modalityDetails
      ? { ...ride.pickup, modalityDetails: ride.modalityDetails, deliveryDetails: ride.deliveryDetails }
      : ride.pickup;
    const destinoWithMeta = ride.modalityDetails
      ? {
          ...ride.destination,
          contactName: ride.modalityDetails.recipientName || ride.destination?.contactName,
          contactPhone: ride.modalityDetails.recipientPhone || ride.destination?.contactPhone,
          modalityDetails: ride.modalityDetails,
        }
      : ride.destination;

    const payload: any = {
      created_at: nowIso,
      data: nowIso,
      email_passageiro: ((ride as any).passengerEmail || currentUser?.email || '').toLowerCase().trim(),
      passageiro_nome: ride.passengerName || currentUser?.name || 'Passageiro',
      nome_passageiro: ride.passengerName || currentUser?.name || 'Passageiro',
      passageiro_foto: ride.passengerAvatar || currentUser?.avatar || '',
      email_motorista: (ride.driver?.email || '').toLowerCase().trim(),
      nome_motorista: ride.driver?.name || '',
      origem: origemWithMeta,
      destino: destinoWithMeta,
      origem_texto: ride.pickup?.address || '',
      destino_texto: ride.destination?.address || '',
      valor: totalPrice,
      valor_total: totalPrice,
      valor_motorista: driverEarnings,
      valor_race: raceFee,
      categoria: getCategoryDisplayLabel(ride.category),
      status: normalizedStatus,
      forma_pagamento: normalizedPaymentMethod,
      rating_dado: ride.ratingGivenToDriver ?? null,
      comentario: ride.ratingComment ?? null,
      detalhe_problema: (ride as any).issueComment ?? null,
      detalhes_modalidade: ride.modalityDetails ? JSON.stringify(ride.modalityDetails) : '',
      codigo_confirmacao: ride.confirmationCode || '',
      asaas_payment_id: ride.asaasPaymentId || '',
      asaas_status: isCash ? 'DINHEIRO' : (ride.asaasStatus || 'PENDING'),
      pagamento_confirmado: isCash || isAsaasConfirmed,
    };

    if (/^\d+$/.test(String(rawPassengerId))) {
      payload.id_passageiro = Number(rawPassengerId);
      payload.passageiro_id = Number(rawPassengerId);
    }
    if (/^\d+$/.test(String(rawDriverId))) {
      payload.id_motorista = Number(rawDriverId);
      payload.motorista_id = Number(rawDriverId);
    }

    // Se a corrida já possui ID numérico gerado pelo Supabase, faz update
    if (ride.id && /^\d+$/.test(String(ride.id))) {
      const { data: updData, error: updErr } = await supabase
        .from('corridas')
        .update(payload)
        .eq('id', Number(ride.id))
        .select();
      if (!updErr && updData && updData.length > 0) {
        return { success: true, id: String(updData[0].id) };
      }
    }

    // Novo registro: INSERT sem campo `id` (Supabase gera o bigint automático)
    const optionalCols = [
      'created_at',
      'passageiro_id',
      'passageiro_nome',
      'passageiro_foto',
      'motorista_id',
      'valor_total',
      'valor_motorista',
      'valor_race',
      'valor',
      'codigo_confirmacao',
      'asaas_payment_id',
      'asaas_status',
      'pagamento_confirmado',
      'id_passageiro',
      'id_motorista',
      'detalhe_problema',
      'detalhes_modalidade',
      'comentario',
      'rating_dado',
      'forma_pagamento',
      'origem_texto',
      'destino_texto',
      'nome_passageiro',
      'nome_motorista',
      'email_passageiro',
      'email_motorista',
      'categoria',
      'data',
    ];

    for (let attempt = 0; attempt < 20; attempt++) {
      const { data, error } = await supabase.from('corridas').insert([payload]).select();
      if (!error) {
        const insertedRow = data?.[0];
        const insertedId = insertedRow?.id !== undefined ? String(insertedRow.id) : undefined;
        if (normalizedStatus === 'procurando') {
          broadcastCorridaEvent('nova_corrida', {
            ...ride,
            id: insertedId || ride.id,
            status: 'procurando',
            driverEarnings,
            platformFee: raceFee,
          });
        }
        return { success: true, id: insertedId };
      }

      const msg = error.message || '';
      let changed = false;
      for (const col of optionalCols) {
        if (col in payload && msg.includes(col)) {
          delete payload[col];
          changed = true;
        }
      }
      if (!changed) {
        const matchCol = msg.match(/'([a-zA-Z0-9_]+)' column/) || msg.match(/column "([a-zA-Z0-9_]+)"/);
        if (matchCol && matchCol[1] && matchCol[1] in payload) {
          delete payload[matchCol[1]];
          changed = true;
        }
      }
      if (!changed && msg.includes('bigint')) {
        for (const idCol of ['id_passageiro', 'passageiro_id', 'id_motorista', 'motorista_id']) {
          if (idCol in payload) {
            delete payload[idCol];
            changed = true;
          }
        }
      }
      if (!changed && (msg.includes('json') || msg.includes('origem') || msg.includes('destino'))) {
        if (typeof payload.origem === 'object') {
          payload.origem = ride.pickup?.address || '';
          changed = true;
        }
        if (typeof payload.destino === 'object') {
          payload.destino = ride.destination?.address || '';
          changed = true;
        }
      }
      if (changed) continue;

      console.warn('Aviso Supabase ao salvar corrida:', msg);
      if (normalizedStatus === 'procurando') {
        broadcastCorridaEvent('nova_corrida', {
          ...ride,
          status: 'procurando',
          driverEarnings,
          platformFee: raceFee,
        });
      }
      return { success: false, error: msg };
    }

    return { success: false, error: 'Não foi possível salvar corrida no Supabase.' };
  } catch (err: any) {
    console.warn('Erro ao salvar corrida no Supabase:', err?.message || err);
    return { success: false, error: err?.message };
  }
}

