export function normalizeRideCategory(rawCat?: string): 'economica' | 'confort' | 'moto_passageiro' | 'moto_entrega' {
  const c = String(rawCat || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
  if (c.includes('confort')) return 'confort';
  if (c.includes('entrega') || c.includes('flash')) return 'moto_entrega';
  if (c.includes('moto')) return 'moto_passageiro';
  return 'economica';
}

export function getCategoryDisplayLabel(rawCat?: string): string {
  const norm = normalizeRideCategory(rawCat);
  if (norm === 'confort') return 'Confort';
  if (norm === 'moto_passageiro') return 'Motoboy Passageiro';
  if (norm === 'moto_entrega') return 'Motoboy Entregas';
  return 'Econômico';
}

function parseLocationField(val: any, fallbackText: string | undefined, defaultLat: number, defaultLng: number) {
  if (val && typeof val === 'object' && typeof val.address === 'string') {
    return {
      address: val.address || fallbackText || '',
      lat: Number(val.lat) || defaultLat,
      lng: Number(val.lng) || defaultLng,
    };
  }
  if (typeof val === 'string') {
    const trimmed = val.trim();
    if (trimmed.startsWith('{')) {
      try {
        const parsed = JSON.parse(trimmed);
        if (parsed && typeof parsed.address === 'string') {
          return {
            address: parsed.address || fallbackText || '',
            lat: Number(parsed.lat) || defaultLat,
            lng: Number(parsed.lng) || defaultLng,
          };
        }
      } catch {}
    }
    return {
      address: trimmed || fallbackText || '',
      lat: defaultLat,
      lng: defaultLng,
    };
  }
  return {
    address: fallbackText || '',
    lat: defaultLat,
    lng: defaultLng,
  };
}

export function mapSupabaseCorridaToRide(row: SupabaseCorridaRow): Ride {
  const driverIdRaw = row.motorista_id ?? row.id_motorista;
  const passengerIdRaw = row.passageiro_id ?? row.id_passageiro;
  const hasDriverAssigned = Boolean(row.email_motorista || row.nome_motorista || driverIdRaw);
  const rawPayment = String(row.forma_pagamento || 'pix').toLowerCase().trim();
  const isCash = rawPayment === 'dinheiro' || rawPayment === 'money';
  const isCard = rawPayment.includes('cart') || rawPayment === 'credit_card';
  const isCredit = rawPayment === 'race_pay' || rawPayment === 'credito';
  const rawStatus = String(row.status || 'completed').toLowerCase().trim();
  const normCategory = normalizeRideCategory(row.categoria);
  const createdTime = row.created_at || row.data || new Date().toISOString();
  const totalValue = Number(row.valor_total ?? row.valor ?? 0);
  const fallbackSplit = calculateRideSplitForDriver(totalValue, undefined, createdTime);
  const driverValue =
    row.valor_motorista !== undefined && row.valor_motorista !== null
      ? Number(row.valor_motorista)
      : fallbackSplit.driverEarnings;
  const raceValue =
    row.valor_race !== undefined && row.valor_race !== null
      ? Number(row.valor_race)
      : fallbackSplit.platformFee;

  const rawAsaasSt = String(row.asaas_status || '').toUpperCase().trim();
  const hasExplicitAsaasStatus = rawAsaasSt.length > 0 && rawAsaasSt !== 'DINHEIRO';
  const isAsaasApproved = rawAsaasSt === 'RECEIVED' || rawAsaasSt === 'CONFIRMED' || rawAsaasSt === 'CREDITO';
  const isPaidDigital = !isCash && (
    isCredit ||
    rawAsaasSt === 'CREDITO' ||
    (hasExplicitAsaasStatus ? isAsaasApproved : row.pagamento_confirmado !== false)
  );

  return {
    id: String(row.id ?? ''),
    passengerId: passengerIdRaw !== undefined && passengerIdRaw !== null ? String(passengerIdRaw) : '',
    passengerEmail: row.email_passageiro,
    passengerName: row.passageiro_nome || row.nome_passageiro || 'Passageiro',
    passengerPhone: '',
    passengerAvatar: row.passageiro_foto || '',
    passengerRating: 0,
    driver: hasDriverAssigned
      ? {
          id: driverIdRaw !== undefined && driverIdRaw !== null ? String(driverIdRaw) : '',
          name: row.nome_motorista || '',
          email: row.email_motorista || '',
          phone: '',
          category: normCategory,
          avatar: '',
          rating: Number(row.rating_dado || 0),
          totalRides: 0,
          vehicleModel: '',
          vehiclePlate: '',
          vehicleColor: '',
          vehicleYear: 2023,
          cpf: '',
          cnh: '',
          weeklyPlanActive: true,
          weeklyPlanPrice: 0,
          status: 'online',
          earningsToday: totalValue,
          earningsWeek: totalValue,
          cnhVerified: true,
          vehicleVerified: true,
          criminalRecordClear: true,
          lat: -23.0842,
          lng: -47.2118,
          registrationDate: createdTime,
        }
      : undefined,
    category: normCategory,
    pickup: parseLocationField(row.origem, row.origem_texto, -23.0842, -47.2118),
    destination: parseLocationField(row.destino, row.destino_texto, -23.0805, -47.2050),
    distanceKm: 0,
    durationMinutes: 0,
    price: totalValue,
    driverEarnings: driverValue,
    platformFee: raceValue,
    paymentMethod: isCash ? 'dinheiro' : isCard ? 'credit_card' : isCredit ? 'race_pay' : 'pix',
    paymentStatus: isCash
      ? (rawStatus !== 'finalizada' && rawStatus !== 'completed' ? 'pending' : 'paid')
      : (isPaidDigital ? 'paid' : 'pending'),
    asaasPaymentId: row.asaas_payment_id || undefined,
    asaasStatus: (hasExplicitAsaasStatus ? rawAsaasSt : undefined) as any,
    status: (row.status as any) || 'procurando',
    confirmationCode: row.codigo_confirmacao || undefined,
    createdAt: createdTime,
    ratingGivenToDriver: row.rating_dado,
    ratingComment: row.comentario,
    issueComment: row.detalhe_problema,
    ...(() => {
      const parseJson = (v: any) => {
        if (!v) return null;
        if (typeof v === 'object') return v;
        if (typeof v === 'string' && v.trim().startsWith('{')) {
          try {
            return JSON.parse(v.trim());
          } catch {
            return null;
          }
        }
        return null;
      };
      const origObj = parseJson(row.origem);
      const destObj = parseJson(row.destino);
      const modalObj = parseJson((row as any).detalhes_modalidade);
      const md = modalObj || origObj?.modalityDetails || destObj?.modalityDetails || undefined;
      const dd = origObj?.deliveryDetails || destObj?.deliveryDetails || undefined;
      const rawCreditUsed = origObj?.creditUsed ?? destObj?.creditUsed;
      const rawOriginalPrice = origObj?.originalPrice ?? destObj?.originalPrice;
      return {
        modalityDetails: md,
        deliveryDetails: dd,
        creditUsed: typeof rawCreditUsed === 'number' ? rawCreditUsed : undefined,
        originalPrice: typeof rawOriginalPrice === 'number' ? rawOriginalPrice : undefined,
      };
    })(),
  };
}

/**
 * Garante que o motoboy só receba entregas completas (descrição, peso, nome e telefone de quem recebe)
 */
export function isDeliveryRideCompleteForDriver(ride?: Ride | null): boolean {
  if (!ride) return false;
  if (normalizeRideCategory(ride.category) !== 'moto_entrega') return true;
  const md = ride.modalityDetails;
  const dd = ride.deliveryDetails;
  const desc = (md?.deliveryDescription || dd?.packageType || '').trim();
  const weight = (md?.deliveryWeight || '').trim();
  const recName = (md?.recipientName || dd?.recipientName || ride.destination?.contactName || '').trim();
  const recPhone = (md?.recipientPhone || ride.destination?.contactPhone || '').replace(/\D/g, '');
  return Boolean(desc && weight && recName && recPhone.length >= 8);
}

/**
 * Garante que o Radar do Motorista só exiba corridas pagas de verdade no Asaas
 * (RECEIVED ou CONFIRMED), pagas com Crédito RACE OU corridas confirmadas em Dinheiro.
 */
export function isRidePaidOrConfirmedCash(ride?: Ride | null): boolean {
  if (!ride) return false;
  const method = String(ride.paymentMethod || '').toLowerCase().trim();
  if (method === 'dinheiro' || method === 'money') {
    return true;
  }
  if (method === 'race_pay' || method === 'credito') {
    return ride.paymentStatus === 'paid' || String(ride.asaasStatus || '').toUpperCase().trim() === 'CREDITO';
  }
  if (ride.asaasStatus) {
    const st = String(ride.asaasStatus).toUpperCase().trim();
    return st === 'RECEIVED' || st === 'CONFIRMED' || st === 'CREDITO';
  }
  return ride.paymentStatus === 'paid';
}

// Cache curto em memória dos perfis/fotos para hidratação instantânea das chamadas sem recarregar a página
let userProfileHydrationCache: Map<string, any> | null = null;
let userProfileHydrationCacheAt = 0;

function indexUsuarioRowIntoMap(map: Map<string, any>, row: any) {
  if (!row || typeof row !== 'object') return;
  if (row.id !== undefined && row.id !== null) {
    map.set(`id:${String(row.id)}`, row);
  }
  const emailVal = String(row['e-mail'] || row.email || '').trim().toLowerCase();
  if (emailVal) {
    map.set(`email:${emailVal}`, row);
  }
  const loginVal = String(row.login || '').trim().toLowerCase();
  if (loginVal) {
    map.set(`email:${loginVal}`, row);
  }
  const phoneDigits = String(row.celular || row.whatsapp || row.telefone || '').replace(/\D/g, '');
  if (phoneDigits.length >= 8) {
    map.set(`phone:${phoneDigits.slice(-11)}`, row);
  }
  const nomeVal = String(row.nome || '').trim().toLowerCase();
  if (nomeVal) {
    map.set(`name:${nomeVal}`, row);
  }
}

async function getUsuariosHydrationLookupMap(forceRefresh: boolean = false): Promise<Map<string, any>> {
  if (
    !forceRefresh &&
    userProfileHydrationCache &&
    Date.now() - userProfileHydrationCacheAt < 8000
  ) {
    return userProfileHydrationCache;
  }

  const map = new Map<string, any>();
  const isAdmin = await isCurrentCallerAdmin();
  if (isAdmin) {
    try {
      const { data } = await selectSafeUsuariosRows();
      if (Array.isArray(data)) {
        data.forEach((row) => indexUsuarioRowIntoMap(map, row));
      }
    } catch {}
  } else {
    const caller = await getCallerSessionIdentity();
    if (caller.email) {
      try {
        const ownRow = await getUsuarioSupabase(caller.email);
        if (ownRow) indexUsuarioRowIntoMap(map, ownRow);
      } catch {}
    }
    try {
      const rpcRes = await supabase.rpc('rpc_get_online_drivers');
      if (!rpcRes.error && Array.isArray(rpcRes.data)) {
        rpcRes.data.forEach((row: any) => indexUsuarioRowIntoMap(map, row));
      }
    } catch {}
  }

  userProfileHydrationCache = map;
  userProfileHydrationCacheAt = Date.now();
  return map;
}

