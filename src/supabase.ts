function parseLocationField(val: any, fallbackText: string | undefined, defaultLat: number, defaultLng: number) {
  if (val && typeof val === 'object' && typeof val.address === 'string') {
    return {
      address: val.address || fallbackText || '',
      lat: Number(val.lat) || defaultLat,
      lng: Number(val.lng) || defaultLng,
    };
  }
  if (typeof val === 'string') {
    const trimmed = val.trim();
    if (trimmed.startsWith('{')) {
      try {
        const parsed = JSON.parse(trimmed);
        if (parsed && typeof parsed.address === 'string') {
          return {
            address: parsed.address || fallbackText || '',
            lat: Number(parsed.lat) || defaultLat,
            lng: Number(parsed.lng) || defaultLng,
          };
        }
      } catch {}
    }
    return {
      address: trimmed || fallbackText || '',
      lat: defaultLat,
      lng: defaultLng,
    };
  }
  return {
    address: fallbackText || '',
    lat: defaultLat,
    lng: defaultLng,
  };
}

