/**
 * 1. INSERT DIRETO NO CADASTRO (Novo Cadastro)
 * Insere na tabela 'usuarios' do Supabase SEM enviar o campo `id`, deixando o banco gerar o bigint automaticamente.
 */
export async function insertUsuarioSupabase(params: {
  codigo_usuario?: string;
  nome: string;
  email: string;
  celular: string;
  whatsapp?: string;
  login?: string;
  senha: string;
  tipo: string;
  categoria?: string;
  placa?: string;
  modelo?: string;
  ano?: number | string;
  cnh?: string;
  foto?: string;
  avatar?: string;
  status?: string;
  plano_ativo?: boolean;
}): Promise<{ success: boolean; data?: any; error?: string }> {
  try {
    const cleanEmail = params.email.trim().toLowerCase();
    const row: any = {
      nome: params.nome.trim(),
      'e-mail': cleanEmail,
      celular: params.celular.trim(),
      whatsapp: (params.whatsapp || params.celular || '').trim(),
      login: (params.login || cleanEmail).trim().toLowerCase(),
      senha: params.senha,
      tipo: params.tipo || 'passenger',
      categoria: params.categoria || null,
      placa: params.placa || null,
      modelo: params.modelo || null,
      ano: params.ano ? String(params.ano) : null,
      cnh: params.cnh || null,
    };
    if (params.codigo_usuario) row.codigo_usuario = params.codigo_usuario;
    const photoValue = params.foto || params.avatar;
    if (photoValue) {
      row.foto = photoValue;
      row.avatar = photoValue;
    }
    if (params.status) row.status = params.status;
    if (typeof params.plano_ativo === 'boolean') row.plano_ativo = params.plano_ativo;

    // Nunca enviar `id` manual para permitir geração automática bigint pelo Supabase
    delete row.id;

    const optionalCols = [
      'codigo_usuario',
      'foto',
      'avatar',
      'whatsapp',
      'login',
      'status',
      'plano_ativo',
      'categoria',
      'placa',
      'modelo',
      'ano',
      'cnh',
      'celular',
    ];

    for (let attempt = 0; attempt < 8; attempt++) {
      const { data, error } = await supabase.from('usuarios').insert([row]).select();
      if (!error) {
        return { success: true, data: data?.[0] };
      }

      const msg = error.message || '';
      if (msg.includes("'e-mail'") || (msg.includes('e-mail') && 'e-mail' in row)) {
        delete row['e-mail'];
        row.email = cleanEmail;
        continue;
      }

      let removedAny = false;
      for (const col of optionalCols) {
        if (col in row && msg.includes(col)) {
          delete row[col];
          removedAny = true;
        }
      }
      if (removedAny) continue;

      return { success: false, error: msg };
    }

    return { success: false, error: 'Não foi possível concluir o cadastro no Supabase.' };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Falha ao conectar com o Supabase' };
  }
}

/**
 * 2. LOGIN DIRETO NO SUPABASE
 * Busca na tabela 'usuarios' pelo email + senha
 */
export async function loginUsuarioSupabase(
  emailInput: string,
  senhaInput: string
): Promise<{ success: boolean; data?: any; error?: string }> {
  const cleanEmail = emailInput.trim().toLowerCase();
  try {
    // 1. Tenta buscar por 'e-mail' e 'senha'
    let { data, error } = await supabase
      .from('usuarios')
      .select('*')
      .eq('e-mail', cleanEmail)
      .eq('senha', senhaInput)
      .maybeSingle();

    // Fallback se a coluna for 'email'
    if (!data && (!error || error.message?.includes('e-mail'))) {
      const retry = await supabase
        .from('usuarios')
        .select('*')
        .eq('email', cleanEmail)
        .eq('senha', senhaInput)
        .maybeSingle();
      if (retry.data) {
        data = retry.data;
        error = retry.error;
      }
    }

    // Fallback se o usuário digitou o campo 'login'
    if (!data) {
      const retryLogin = await supabase
        .from('usuarios')
        .select('*')
        .eq('login', cleanEmail)
        .eq('senha', senhaInput)
        .maybeSingle();
      if (retryLogin.data) {
        data = retryLogin.data;
        error = retryLogin.error;
      }
    }

    if (error && !error.message?.includes('e-mail') && !error.message?.includes('login')) {
      return { success: false, error: error.message };
    }

    if (!data) {
      return { success: false, error: 'Usuário não encontrado ou senha incorreta no Supabase.' };
    }

    return { success: true, data };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Falha de conexão com o Supabase' };
  }
}

