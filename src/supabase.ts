function formatSupabaseError(error: any): string {
  if (!error) return 'Erro desconhecido ao acessar o Supabase.';
  if (isMissingColumnError(error)) {
    return 'Cadastro compatível com as colunas existentes do banco.';
  }
  const parts = [
    error.message,
    error.details && error.details !== error.message ? error.details : '',
    error.hint ? `Dica: ${error.hint}` : '',
    error.code ? `(código ${error.code})` : '',
  ].filter(Boolean);
  return parts.join(' — ') || String(error);
}

function extractMissingColumnFromSupabaseError(msg: string): string | null {
  if (!msg) return null;
  const pgrstMatch = msg.match(/Could not find the '([^']+)' column/i);
  if (pgrstMatch?.[1]) return pgrstMatch[1];
  const pgQuoteMatch = msg.match(/column "([^"]+)" of relation/i);
  if (pgQuoteMatch?.[1]) return pgQuoteMatch[1];
  const pgQualifiedQuoteMatch = msg.match(/column (?:[a-zA-Z0-9_]+\.)?"([^"]+)" does not exist/i);
  if (pgQualifiedQuoteMatch?.[1]) return pgQualifiedQuoteMatch[1];
  const pgPlainMatch = msg.match(/column (?:[a-zA-Z0-9_]+\.)?([a-zA-Z0-9_-]+) does not exist/i);
  if (pgPlainMatch?.[1]) return pgPlainMatch[1];
  return null;
}

function isMissingColumnError(error: any): boolean {
  if (!error) return false;
  const code = String(error.code || '');
  const msg = String(error.message || '').toLowerCase();
  return (
    code === '42703' ||
    code === 'PGRST204' ||
    msg.includes('does not exist') ||
    msg.includes('could not find the')
  );
}

let cachedUsuariosColumns: Set<string> | null = null;
let cachedUsuariosColumnsAt = 0;

export async function getUsuariosTableColumns(forceRefresh: boolean = false): Promise<Set<string> | null> {
  if (!forceRefresh && cachedUsuariosColumns && Date.now() - cachedUsuariosColumnsAt < 5 * 60 * 1000) {
    return cachedUsuariosColumns;
  }

  // 1. Descobre colunas reais pelo schema OpenAPI do PostgREST (funciona mesmo com tabela vazia ou RLS)
  try {
    const resp = await fetch(`${SUPABASE_URL}/rest/v1/`, {
      headers: {
        apikey: SUPABASE_ANON_KEY,
        Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
        Accept: 'application/openapi+json, application/json',
      },
    });
    if (resp.ok) {
      const spec = await resp.json();
      const props =
        spec?.definitions?.usuarios?.properties ||
        spec?.components?.schemas?.usuarios?.properties;
      if (props && typeof props === 'object') {
        const cols = new Set(Object.keys(props));
        if (cols.size > 0) {
          cachedUsuariosColumns = cols;
          cachedUsuariosColumnsAt = Date.now();
          return cols;
        }
      }
    }
  } catch {}

  // 2. Fallback via select('*').limit(1) (nunca dispara erro 42703)
  try {
    const { data, error } = await supabase.from('usuarios').select('*').limit(1);
    if (!error && Array.isArray(data) && data.length > 0 && data[0]) {
      const cols = new Set(Object.keys(data[0]));
      cachedUsuariosColumns = cols;
      cachedUsuariosColumnsAt = Date.now();
      return cols;
    }
  } catch {}

  return cachedUsuariosColumns;
}

