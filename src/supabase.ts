/**
 * Atualiza imediatamente status ONLINE/OFFLINE e GPS do motorista no Supabase
 */
export async function updateDriverOnlineStatusSupabase(params: {
  id?: string | number;
  email?: string;
  status: 'online' | 'offline';
  lat?: number;
  lng?: number;
}): Promise<boolean> {
  try {
    const payload: Record<string, any> = {
      status: params.status,
      online: params.status === 'online',
    };
    if (typeof params.lat === 'number' && !Number.isNaN(params.lat)) {
      payload.lat = params.lat;
    }
    if (typeof params.lng === 'number' && !Number.isNaN(params.lng)) {
      payload.lng = params.lng;
    }

    const executeUpdate = async (body: Record<string, any>) => {
      if (params.id && /^\d+$/.test(String(params.id))) {
        return supabase.from('usuarios').update(body).eq('id', Number(params.id));
      }
      if (params.email) {
        const clean = params.email.trim().toLowerCase();
        const res = await supabase.from('usuarios').update(body).eq('e-mail', clean);
        if (res.error && res.error.message?.includes('e-mail')) {
          return supabase.from('usuarios').update(body).eq('email', clean);
        }
        return res;
      }
      return { error: { message: 'Sem identificador' } } as any;
    };

    for (let attempt = 0; attempt < 4; attempt++) {
      const res = await executeUpdate({ ...payload });
      if (!res.error) return true;
      const msg = res.error.message || '';
      let removed = false;
      for (const col of ['online', 'lat', 'lng']) {
        if (col in payload && msg.includes(col)) {
          delete payload[col];
          removed = true;
        }
      }
      if (!removed) return false;
    }
    return false;
  } catch {
    return false;
  }
}

