export function purgeLegacyTestLocalStorage(preserveCurrentSession: boolean = true): void {
  if (typeof window === 'undefined') return;
  try {
    const exactKeysToRemove = [
      'race_registered_drivers',
      'race_registered_passengers',
      'race_users',
      'race_rides_history',
      'race_active_ride',
      'race_driver_balances',
      'race_withdrawals',
      'race_weekly_fee_deducted',
      'race_driver_reviews',
      'race_last_confirmation_code',
      'race_admin_custom_password',
      'race_asaas_api_key',
    ];
    if (!preserveCurrentSession) {
      exactKeysToRemove.push('race_current_user', 'race_usuario_logado');
    }
    exactKeysToRemove.forEach((k) => {
      try {
        localStorage.removeItem(k);
      } catch {}
    });

    const dynamicKeys: string[] = [];
    for (let i = 0; i < localStorage.length; i++) {
      const k = localStorage.key(i);
      if (
        k &&
        (k.startsWith('race_user_') ||
          k.startsWith('race_rides_') ||
          k.startsWith('asaas_status_'))
      ) {
        dynamicKeys.push(k);
      }
    }
    dynamicKeys.forEach((k) => {
      try {
        localStorage.removeItem(k);
      } catch {}
    });
  } catch {}
}

export function setDriverRequirementsConfirmedLocal(email: string, confirmed: boolean): void {
  if (typeof window === 'undefined' || !email) return;
  try {
    const key = `race_req_confirmed_${email.trim().toLowerCase()}`;
    if (confirmed) {
      localStorage.setItem(key, 'true');
    } else {
      localStorage.removeItem(key);
    }
  } catch {}
}

export function getDriverRequirementsConfirmedLocal(email: string): boolean {
  if (typeof window === 'undefined' || !email) return false;
  try {
    return localStorage.getItem(`race_req_confirmed_${email.trim().toLowerCase()}`) === 'true';
  } catch {
    return false;
  }
}

function formatSupabaseError(error: any): string {
  if (!error) return 'Erro desconhecido ao acessar o Supabase.';
  const parts = [
    error.message,
    error.details && error.details !== error.message ? error.details : '',
    error.hint ? `Dica: ${error.hint}` : '',
    error.code ? `(código ${error.code})` : '',
  ].filter(Boolean);
  return parts.join(' — ') || String(error);
}

function extractMissingColumnFromSupabaseError(msg: string): string | null {
  if (!msg) return null;
  const pgrstMatch = msg.match(/Could not find the '([^']+)' column/i);
  if (pgrstMatch?.[1]) return pgrstMatch[1];
  const pgQuoteMatch = msg.match(/column "([^"]+)" of relation/i);
  if (pgQuoteMatch?.[1]) return pgQuoteMatch[1];
  const pgPlainMatch = msg.match(/column ([a-zA-Z0-9_-]+) does not exist/i);
  if (pgPlainMatch?.[1]) return pgPlainMatch[1];
  return null;
}

