/**
 * ADM corrige/vincula manualmente quem indicou um usuário já cadastrado (ex: Antônio Carlos -> JOSE492 / ID 33).
 * Salva indicado_por, codigo_usado e indicado_por_codigo no Supabase (usuarios + fallback pagamentos).
 */
export async function fixUserReferralAdminSupabase(params: {
  targetUserId: string | number;
  targetEmail?: string;
  referralCode: string;
}): Promise<{
  success: boolean;
  referrerId?: string;
  referralCode?: string;
  referrerName?: string;
  error?: string;
}> {
  const cleanCode = normalizeReferralCodeInput(params.referralCode);
  if (!cleanCode) {
    return { success: false, error: 'Informe um código de indicação válido (ex: JOSE492).' };
  }

  const targetIdStr = String(params.targetUserId ?? '').trim();
  const targetEmailClean = String(params.targetEmail || '').trim().toLowerCase();

  try {
    const resolved = await resolveReferrerByCodeSupabase(cleanCode);
    if (!resolved.valid) {
      return { success: false, error: resolved.error || INVALID_REFERRAL_CODE_ERROR };
    }

    const refId = resolved.referrerId ? String(resolved.referrerId).trim() : '';
    const refEmail = resolved.referrerEmail ? String(resolved.referrerEmail).trim().toLowerCase() : '';
    if ((targetIdStr && refId && targetIdStr === refId) || (targetEmailClean && refEmail && targetEmailClean === refEmail)) {
      return { success: false, error: 'Um usuário não pode ser vinculado ao próprio código.' };
    }

    const indicatedPorValue = refId || resolved.normalizedCode;
    const knownCols = await getUsuariosTableColumns(true);

    const updatePayload: Record<string, any> = {};
    if (!knownCols || knownCols.size === 0 || knownCols.has('indicado_por')) {
      updatePayload.indicado_por = indicatedPorValue;
    }
    if (!knownCols || knownCols.size === 0 || knownCols.has('codigo_usado')) {
      updatePayload.codigo_usado = resolved.normalizedCode;
    }
    if (!knownCols || knownCols.size === 0 || knownCols.has('indicado_por_codigo')) {
      updatePayload.indicado_por_codigo = resolved.normalizedCode;
    }

    if (Object.keys(updatePayload).length > 0 && /^\d+$/.test(targetIdStr)) {
      for (let attempt = 0; attempt < 5; attempt++) {
        if (Object.keys(updatePayload).length === 0) break;
        const { error } = await supabase
          .from('usuarios')
          .update(updatePayload)
          .eq('id', Number(targetIdStr));
        if (!error) break;
        if (isMissingColumnError(error)) {
          const missing = extractMissingColumnFromSupabaseError(error.message || '');
          if (missing && missing in updatePayload) {
            delete updatePayload[missing];
            continue;
          }
          for (const k of Object.keys(updatePayload)) {
            if ((error.message || '').includes(k)) {
              delete updatePayload[k];
            }
          }
          continue;
        }
        break;
      }
    }

    const linkSaved = await upsertReferralLinkInPagamentos({
      referrerId: refId || null,
      indicatedId: targetIdStr || null,
      indicatedEmail: targetEmailClean || null,
      referralCode: resolved.normalizedCode,
    });

    const wroteUsuarioCols = Object.keys(updatePayload).length > 0;
    if (!wroteUsuarioCols && !linkSaved) {
      return {
        success: false,
        error: 'Não foi possível salvar o vínculo no Supabase. Verifique permissões/RLS.',
      };
    }

    return {
      success: true,
      referrerId: refId || undefined,
      referralCode: resolved.normalizedCode,
      referrerName: resolved.referrerName,
    };
  } catch (err: any) {
    return {
      success: false,
      error: err?.message || 'Erro ao corrigir indicação no Supabase.',
    };
  }
}

/**
 * ADM marca bônus de indicação como PAGO (sexta-feira via PIX ou crédito liberado)
 * Trava rigorosa: 1 indicado = 1 bônus só, nunca pode pagar 2 vezes.
 */
export async function markReferralBonusPaidByAdminSupabase(params: {
  indicatedId: string;
  indicatedName: string;
  indicatedEmail: string;
  indicatedRole: 'passenger' | 'driver';
  ridesCount: number;
  requiredRides: number;
  bonusAmount: number;
  referrerId?: string | number | null;
  referrerName: string;
  referrerEmail: string;
  existingPaymentId?: string | number | null;
  existingComprovanteUrl?: string | null;
}): Promise<{
  success: boolean;
  alreadyLocked?: boolean;
  paidAt?: string;
  paymentRow?: SupabasePagamentoRow;
  error?: string;
}> {
  const cleanIndicatedId = String(params.indicatedId || '').trim();
  const cleanIndicatedEmail = String(params.indicatedEmail || '').trim().toLowerCase();
  const dedupKey = cleanIndicatedId ? `INDICADO:${cleanIndicatedId}` : '';

  try {
    // 1. Verifica trava no Supabase antes de qualquer escrita (1 indicado = 1 bônus só)
    const { data: existingRows } = await supabase
      .from('pagamentos')
      .select('*')
      .eq('tipo', 'bonus_indicacao')
      .limit(200);

    const matchedRow = (existingRows || []).find((p: any) => {
      if (dedupKey && String(p.chave_pix || '').trim() === dedupKey) return true;
      if (cleanIndicatedEmail && String(p.comprovante_url || '').toLowerCase().includes(cleanIndicatedEmail)) {
        return true;
      }
      return false;
    });

    const targetRow = matchedRow || (params.existingPaymentId ? { id: params.existingPaymentId, comprovante_url: params.existingComprovanteUrl } : null);

    if (targetRow && targetRow.comprovante_url) {
      try {
        const parsed = JSON.parse(String(targetRow.comprovante_url));
        if (parsed?.paidFriday === true || String((targetRow as any).status || '').toLowerCase() === 'pago_sexta') {
          return {
            success: false,
            alreadyLocked: true,
            paidAt: parsed?.paidAt || (targetRow as any).data || undefined,
          };
        }
      } catch {}
    }

    const paidAtIso = new Date().toISOString();
    const metaPayload = JSON.stringify({
      indicatedId: cleanIndicatedId,
      indicatedName: params.indicatedName || 'Indicado',
      indicatedEmail: cleanIndicatedEmail,
      indicatedRole: params.indicatedRole,
      ridesCount: params.ridesCount,
      requiredRides: params.requiredRides,
      paidFriday: true,
      paidAt: paidAtIso,
      locked: true,
    });

    if (targetRow && targetRow.id) {
      const { data: updatedData, error: updErr } = await supabase
        .from('pagamentos')
        .update({
          status: 'pago_sexta',
          comprovante_url: metaPayload,
          data: paidAtIso,
        })
        .eq('id', targetRow.id)
        .select()
        .single();

      if (updErr) {
        return { success: false, error: updErr.message };
      }
      if (cleanIndicatedId && /^\d+$/.test(cleanIndicatedId)) {
        await supabase.from('usuarios').update({ bonus_pago: true }).eq('id', Number(cleanIndicatedId));
      }
      return { success: true, paidAt: paidAtIso, paymentRow: updatedData as SupabasePagamentoRow };
    }

    const numericReferrerId =
      params.referrerId && /^\d+$/.test(String(params.referrerId)) ? Number(params.referrerId) : null;

    const { data: insertedData, error: insErr } = await supabase
      .from('pagamentos')
      .insert({
        id_motorista: numericReferrerId,
        nome_motorista: params.referrerName || 'Indicador',
        email_motorista: String(params.referrerEmail || '').trim().toLowerCase(),
        valor: params.bonusAmount,
        tipo: 'bonus_indicacao',
        status: 'pago_sexta',
        chave_pix: dedupKey || `INDICADO_EMAIL:${cleanIndicatedEmail}`,
        comprovante_url: metaPayload,
        data: paidAtIso,
      })
      .select()
      .single();

    if (insErr) {
      return { success: false, error: insErr.message };
    }

    if (cleanIndicatedId && /^\d+$/.test(cleanIndicatedId)) {
      await supabase.from('usuarios').update({ bonus_pago: true }).eq('id', Number(cleanIndicatedId));
    }

    return { success: true, paidAt: paidAtIso, paymentRow: insertedData as SupabasePagamentoRow };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Erro ao marcar pagamento do bônus.' };
  }
}


