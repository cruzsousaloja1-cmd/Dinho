/**
 * Verifica se e-mail ou login já está cadastrado no Supabase via RPC segura (nunca lista usuarios)
 */
export async function checkEmailExistsSupabase(emailOrLogin: string): Promise<boolean> {
  const clean = normalizeEmailNoSpaces(emailOrLogin);
  if (!clean) return false;
  try {
    const rpcRes = await supabase.rpc('rpc_check_email_exists', { p_email: clean });
    if (!rpcRes.error && typeof rpcRes.data === 'boolean') {
      return rpcRes.data;
    }
  } catch {}

  const existing = await getUsuarioSupabase(clean);
  if (existing) return true;

  return false;
}

/**
 * Verifica se WhatsApp/celular já está cadastrado no Supabase via RPC segura (nunca lista usuarios)
 */
export async function checkWhatsAppExistsSupabase(whatsapp: string): Promise<boolean> {
  const cleanDigits = normalizePhoneDigitsOnly(whatsapp);
  if (cleanDigits.length < 8) return false;

  try {
    const rpcRes = await supabase.rpc('rpc_check_whatsapp_exists', { p_whatsapp: cleanDigits });
    if (!rpcRes.error && typeof rpcRes.data === 'boolean') {
      return rpcRes.data;
    }
  } catch {}

  return false;
}

/**
 * Verificação única de duplicidade antes de qualquer cadastro (E-mail e WhatsApp)
 */
export async function checkDuplicateRegistrationSupabase(params: {
  email: string;
  whatsapp: string;
  login?: string;
}): Promise<{
  isDuplicate: boolean;
  field?: 'email' | 'whatsapp';
  message?: string;
}> {
  const cleanEmail = normalizeEmailNoSpaces(params.email);
  const cleanWhatsapp = normalizePhoneDigitsOnly(params.whatsapp);
  const cleanLogin = normalizeEmailNoSpaces(params.login || '');

  const [emailExists, whatsappExists, loginExists] = await Promise.all([
    cleanEmail ? checkEmailExistsSupabase(cleanEmail).catch(() => false) : Promise.resolve(false),
    cleanWhatsapp.length >= 8 ? checkWhatsAppExistsSupabase(cleanWhatsapp).catch(() => false) : Promise.resolve(false),
    cleanLogin && cleanLogin !== cleanEmail
      ? checkEmailExistsSupabase(cleanLogin).catch(() => false)
      : Promise.resolve(false),
  ]);

  if (emailExists || loginExists) {
    return {
      isDuplicate: true,
      field: 'email',
      message: 'Este e-mail já está cadastrado. Clique em Entrar ou em Esqueci minha senha.',
    };
  }

  if (whatsappExists) {
    return {
      isDuplicate: true,
      field: 'whatsapp',
      message: 'Este WhatsApp já está cadastrado. Use outro WhatsApp ou entre com seu cadastro.',
    };
  }

  return { isDuplicate: false };
}

/**
 * Busca usuário por e-mail ou login no Supabase sem retornar `senha` e sem erro 42703
 */
export async function getUsuarioSupabase(emailOrLogin: string): Promise<any | null> {
  const clean = emailOrLogin.trim().toLowerCase();
  if (!clean) return null;

  try {
    const knownCols = await getUsuariosTableColumns();
    const lookupCols = ['email', 'e-mail', 'login'].filter(
      (col) => !knownCols || knownCols.size === 0 || knownCols.has(col)
    );

    for (const col of lookupCols) {
      const res = await selectSafeUsuariosRows((q) => q.eq(col, clean).limit(1));
      if (res.data && res.data.length > 0) return res.data[0];
    }

    // Fallback seguro via RPC caso RLS restrinja SELECT direto
    try {
      const rpcRes = await supabase.rpc('rpc_login_usuario', { p_identifier: clean });
      if (!rpcRes.error && rpcRes.data) {
        return stripSensitiveUserFields(rpcRes.data);
      }
    } catch {}
  } catch (err) {
    console.warn('Aviso ao consultar Supabase:', err);
  }

  return null;
}

/**
 * Atualiza senha fazendo as DUAS operações juntas:
 * 1) supabase.auth.updateUser({ password: newPassword })
 * 2) update em public.usuarios { senha: newPassword } (quando coluna existir)
 * Caso não haja sessão ativa para o e-mail, envia resetPasswordForEmail com redirectTo de produção (/Dinho/).
 */
export async function updatePasswordSupabase(
  identifier: string,
  newPassword: string,
  _fallbackNome?: string
): Promise<{ success: boolean; sentResetEmail?: boolean; error?: string }> {
  const clean = identifier.trim().toLowerCase();
  if (!clean || !newPassword || newPassword.length < 6) {
    return { success: false, error: 'Identificador ou senha inválidos (mínimo 6 caracteres).' };
  }

  try {
    let targetEmail = clean;
    if (!targetEmail.includes('@')) {
      const found = await getUsuarioSupabase(clean).catch(() => null);
      const resolved = String(found?.['e-mail'] || found?.email || '').trim().toLowerCase();
      if (resolved && resolved.includes('@')) {
        targetEmail = resolved;
      }
    }

    const syncUsuariosSenhaRow = async () => {
      const knownCols = await getUsuariosTableColumns().catch(() => null);
      if (knownCols && knownCols.size > 0 && !knownCols.has('senha')) {
        return { error: null };
      }
      const matchCols = ['email', 'e-mail'].filter(
        (col) => !knownCols || knownCols.size === 0 || knownCols.has(col)
      );
      for (const col of matchCols) {
        const res = await supabase
          .from('usuarios')
          .update({ senha: newPassword })
          .eq(col, targetEmail);
        if (!res.error) return { error: null };
        if (isMissingColumnError(res.error)) {
          const msg = res.error.message || '';
          if (msg.includes('senha')) return { error: null };
          continue;
        }
        return { error: res.error };
      }
      return { error: null };
    };

    const { data: sessionData } = await supabase.auth.getSession();
    const activeAuthEmail = String(sessionData?.session?.user?.email || '').trim().toLowerCase();

    if (activeAuthEmail && activeAuthEmail === targetEmail) {
      const [authRes, tableRes] = await Promise.all([
        supabase.auth.updateUser({ password: newPassword }),
        syncUsuariosSenhaRow(),
      ]);

      if (authRes.error) {
        return {
          success: false,
          error: authRes.error.message || 'Erro ao atualizar senha no Supabase Auth.',
        };
      }
      if (tableRes.error) {
        return {
          success: false,
          error: formatSupabaseError(tableRes.error) || 'Erro ao atualizar senha na tabela usuarios.',
        };
      }
      return { success: true };
    }

    const { error: resetError } = await supabase.auth.resetPasswordForEmail(targetEmail, {
      redirectTo: PRODUCTION_REDIRECT_URL,
    });
    if (resetError) {
      const errLower = (resetError.message || '').toLowerCase();
      if (errLower.includes('rate limit') || errLower.includes('too many requests')) {
        return {
          success: false,
          error:
            'Limite temporário de envios de e-mail do Supabase atingido (1 hora). Aguarde alguns minutos antes de solicitar outro e-mail de redefinição.',
        };
      }
      return {
        success: false,
        error: resetError.message || 'Não foi possível enviar redefinição pelo Supabase Auth.',
      };
    }
    return { success: true, sentResetEmail: true };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Erro ao atualizar senha no Supabase Auth.' };
  }
}

